"""Write test/cases/types/c18_from_shapes.sql: query features that the dialect rewrites by changing what a query
block's FROM looks like (nested windows, window / session_window grouping, LATERAL VIEW, ...) crossed with the shapes
a FROM can have (one table, a subquery, a CTE, joins with ON / USING / a comma, an alias that is also a column name).

A rewrite that wraps the FROM in a derived table can lose the names the query uses (a join has no single alias), so
every feature reads its columns with table qualifiers. Expectations come from Spark (test/make_golden.py).
Deterministic.

usage: python scripts/gen_from_shape_cases.py
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "test" / "cases" / "types" / "c18_from_shapes.sql"

SETUP = [
    "CREATE TEMPORARY VIEW c18_a AS SELECT * FROM VALUES\n"
    "  (1, 10, TIMESTAMP '2024-01-01 00:00:00'), (1, 20, TIMESTAMP '2024-01-01 00:03:00'),\n"
    "  (1, 30, TIMESTAMP '2024-01-01 00:20:00'), (2, 40, TIMESTAMP '2024-01-01 00:01:00'),\n"
    "  (3, 50, TIMESTAMP '2024-01-01 00:30:00'), (4, CAST(NULL AS INT), CAST(NULL AS TIMESTAMP)) AS c18_a(k, v, ts)",
    "CREATE TEMPORARY VIEW c18_b AS SELECT * FROM VALUES (1, 'x'), (2, 'y'), (3, CAST(NULL AS STRING)), (5, 'z')\n"
    "  AS c18_b(k, s)",
    "CREATE TEMPORARY VIEW c18_ab AS SELECT a.k, a.v, a.ts, b.s FROM c18_a a JOIN c18_b b ON a.k = b.k",
]

# name: (prefix, FROM, join condition for WHERE or None, name of the table with k / v / ts, name of the table with s)
SHAPES = {
    "table_alias": ("", "c18_ab t", None, "t", "t"),
    "table_name": ("", "c18_ab", None, "c18_ab", "c18_ab"),
    "subquery": ("", "(SELECT * FROM c18_ab) t", None, "t", "t"),
    "cte": ("WITH t AS (SELECT * FROM c18_ab) ", "t", None, "t", "t"),
    "join_on": ("", "c18_a a JOIN c18_b b ON a.k = b.k", None, "a", "b"),
    "left_join_on": ("", "c18_a a LEFT JOIN c18_b b ON a.k = b.k", None, "a", "b"),
    "join_on_table_names": ("", "c18_a JOIN c18_b ON c18_a.k = c18_b.k", None, "c18_a", "c18_b"),
    "join_using": ("", "c18_a a JOIN c18_b b USING (k)", None, "a", "b"),
    "comma_join": ("", "c18_a a, c18_b b", "a.k = b.k", "a", "b"),
    "join_subqueries": ("", "(SELECT * FROM c18_a) a JOIN (SELECT * FROM c18_b) b ON a.k = b.k", None, "a", "b"),
    "join_ctes": ("WITH ca AS (SELECT * FROM c18_a), cb AS (SELECT * FROM c18_b) ", "ca a JOIN cb b ON a.k = b.k",
                  None, "a", "b"),
    # table aliases that are also column names (k.k, s.s)
    "join_alias_is_column": ("", "c18_a k JOIN c18_b s ON k.k = s.k", None, "k", "s"),
}

# name: template over {a} / {b} (table names), {from} and {where} / {and_where} (the shape's join condition)
FEATURES = {
    "nested_window": "SELECT {a}.k, {a}.v, rank() OVER (PARTITION BY {a}.k ORDER BY row_number() OVER "
                     "(ORDER BY {a}.v DESC, {b}.s)) AS r FROM {from} {where}",
    "nested_window_order_by": "SELECT {b}.s, rank() OVER (ORDER BY sum({a}.v) OVER (PARTITION BY {b}.s), {a}.v) AS r "
                              "FROM {from} {where} ORDER BY {a}.v",
    "nested_window_qualified_star": "SELECT {b}.*, rank() OVER (ORDER BY row_number() OVER (ORDER BY {a}.v)) AS r "
                                    "FROM {from} {where}",
    "nested_window_star": "SELECT *, dense_rank() OVER (ORDER BY max({a}.v) OVER (PARTITION BY {b}.s)) AS r "
                          "FROM {from} {where}",
    "window_group_by": "SELECT {b}.s, window.start, count(*), sum({a}.v) FROM {from} {where} "
                       "GROUP BY {b}.s, window({a}.ts, '10 minutes')",
    "session_window_group_by": "SELECT {b}.s, session_window.start, session_window.end, count(*) FROM {from} {where} "
                               "GROUP BY {b}.s, session_window({a}.ts, '5 minutes')",
    "lateral_view": "SELECT {a}.k, {b}.s, e FROM {from} LATERAL VIEW explode(array({a}.v, {a}.v + 1)) lv AS e {where}",
    # the subquery's own columns (xk, xs) do not shadow the outer table names (k, s in join_alias_is_column)
    "correlated_exists": "SELECT {a}.k, {a}.v FROM {from} WHERE {and_where}EXISTS "
                         "(SELECT 1 FROM VALUES (1, 'x'), (2, 'y') AS x(xk, xs) WHERE x.xk = {a}.k AND x.xs = {b}.s)",
    "order_by_hidden_column": "SELECT {b}.s FROM {from} {where} ORDER BY {a}.v DESC NULLS LAST",
    "group_by_rollup": "SELECT {a}.k, {b}.s, sum({a}.v), count({a}.ts) FROM {from} {where} GROUP BY ROLLUP({a}.k, {b}.s)",
}


def emit():
    lines = ["-- C18 FROM shapes: query features the dialect rewrites, over every shape of FROM (table, subquery, CTE,",
             "-- joins with ON / USING / a comma, an alias that is also a column name). Columns are read with table",
             "-- qualifiers. Generated by scripts/gen_from_shape_cases.py; do not edit. Expectations come from Spark.",
             ""]
    for statement in SETUP:
        lines += ["-- @setup", statement + ";", ""]
    n = 0
    for feature, template in FEATURES.items():
        for shape, (prefix, source, condition, a, b) in SHAPES.items():
            sql = prefix + template.format(a=a, b=b, **{"from": source},
                                           where=f"WHERE {condition}" if condition else "",
                                           and_where=f"{condition} AND " if condition else "")
            lines += [f"-- @compose {feature} from={shape}", " ".join(sql.split()) + ";", ""]
            n += 1
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines))
    print(f"wrote {n} cases to {OUT}")


if __name__ == "__main__":
    emit()
