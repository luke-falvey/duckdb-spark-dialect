"""Write test/cases/types/c17_type_names.sql: every type name and alias DuckDB knows (duckdb_types()) plus Spark's own,
written where SQL names a type (CAST, nested in ARRAY<...>, a CREATE TABLE column). Spark's answer decides which
names spark_strict must reject (docs/plans/user-feedback-fixes.md 3.7). Deterministic: the list is fixed below so the
file does not change with the DuckDB version; regenerate the list with --refresh.

usage: python scripts/gen_type_name_cases.py [--refresh]
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "test" / "cases" / "types" / "c17_type_names.sql"

# duckdb_types() of DuckDB 2.0 (system catalog), without the parametric-only names (enum, union, list, map, struct,
# array, row, tuple, type, variant, geometry, logical, integral, signed, null)
DUCKDB_TYPES = ['JSON', 'bigint', 'bignum', 'binary', 'bit', 'bitstring', 'blob', 'bool', 'boolean', 'bpchar', 'bytea',
                'char', 'date', 'datetime', 'dec', 'decimal', 'double', 'float', 'float4', 'float8', 'guid', 'hugeint',
                'int', 'int1', 'int128', 'int16', 'int2', 'int32', 'int4', 'int64', 'int8', 'integer', 'interval',
                'long', 'numeric', 'nvarchar', 'oid', 'real', 'short', 'smallint', 'string', 'text', 'time',
                'time with time zone', 'time_ns', 'timestamp', 'timestamp with time zone', 'timestamp_ms',
                'timestamp_ns', 'timestamp_s', 'timestamp_us', 'timestamptz', 'timestamptz_ns', 'timetz', 'tinyint',
                'ubigint', 'uhugeint', 'uint128', 'uint16', 'uint32', 'uint64', 'uint8', 'uinteger', 'usmallint',
                'utinyint', 'uuid', 'varbinary', 'varchar', 'varint']
SPARK_TYPES = ['byte', 'timestamp_ntz', 'timestamp_ltz', 'void', 'character', 'varchar(5)', 'char(5)', 'character(5)',
               'decimal(5,2)', 'dec(5,2)', 'numeric(5,2)', 'interval day', 'interval year to month']
PARAMETRIC = ['varchar(5)', 'decimal(5,2)', 'bpchar(5)', 'nvarchar(5)', 'text(5)', 'string(5)', 'timestamp(3)',
              'float(10)', 'double precision', 'int(5)']


def refresh():
    import duckdb
    rows = duckdb.connect().execute("SELECT DISTINCT type_name FROM duckdb_types() WHERE database_name = 'system' "
                                    "ORDER BY 1").fetchall()
    print([r[0] for r in rows])


def emit():
    names = []
    for n in DUCKDB_TYPES + SPARK_TYPES + PARAMETRIC:
        if n.lower() not in [x.lower() for x in names]:
            names.append(n)
    lines = ["-- C17 type names: every DuckDB type name and alias, and Spark's, where SQL names a type.",
             "-- Generated by scripts/gen_type_name_cases.py; do not edit. Expectations come from Spark.", ""]
    n = 0
    for i, name in enumerate(names):
        for sql in (f"SELECT typeof(CAST(NULL AS {name}))",
                    f"SELECT typeof(CAST(NULL AS ARRAY<{name}>))",
                    f"CREATE TABLE c17_t{i} (c {name}) USING parquet"):
            lines.append(sql + ";")
            lines.append("")
            n += 1
    OUT.write_text("\n".join(lines))
    print(f"wrote {n} cases to {OUT}")


if __name__ == "__main__":
    refresh() if "--refresh" in sys.argv else emit()
