"""Generate src/spark_conf_registry.inc, the table of Spark settings the dialect knows (key, default, value kind, class,
status, legal enum values), from test/settings/inventory.toml.

usage: python scripts/gen_conf_registry.py [--check]
"""
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "src" / "spark_conf_registry.inc"

KINDS = {"boolean": "BOOLEAN", "int": "INTEGER", "long": "INTEGER", "double": "DOUBLE", "bytes": "BYTES", "time": "TIME",
         "enum": "ENUM", "string": "STRING", "static": "STATIC"}
CLASSES = {"semantic": "SEMANTIC", "command": "COMMAND", "storage": "STORAGE", "execution": "EXECUTION",
           "client": "CLIENT", "static": "STATIC", "unobservable": "UNOBSERVABLE"}
STATUSES = {"emulated": "EMULATED", "partial": "PARTIAL", "accepted": "ACCEPTED", "rejected": "REJECTED"}


def c_string(text):
    return '"' + str(text).replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    inventory = tomllib.loads((ROOT / "test" / "settings" / "inventory.toml").read_text())["keys"]
    lines = ["// Generated by scripts/gen_conf_registry.py from test/settings/inventory.toml: do not edit.",
             "// {key, default, kind, class, status, tier, legal values (enum) or emulated values (partial)}"]
    for key in sorted(inventory):
        e = inventory[key]
        values = e["values"] if e["kind"] == "enum" or e["status"] == "partial" else []
        # a partially emulated key lists the values the dialect accepts
        lines.append("{%s, %s, ConfKind::%s, ConfClass::%s, ConfStatus::%s, %d, %s}," % (
            c_string(key), c_string(e["default"]), KINDS[e["kind"]], CLASSES[e["class"]], STATUSES[e["status"]],
            e.get("tier", 0), c_string("|".join(values))))
    text = "\n".join(lines) + "\n"
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            sys.exit(1)
        return
    OUT.write_text(text)
    print(f"wrote {OUT} ({len(inventory)} keys)")


if __name__ == "__main__":
    main()
