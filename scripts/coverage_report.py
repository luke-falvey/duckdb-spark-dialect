"""Write COVERAGE.md from the last run of test/run_duckdb.py (test/results/)."""
import json, re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
docs = json.loads((ROOT / "test" / "spark35_function_docs.json").read_text())
funcs = json.loads((ROOT / "test" / "results" / "functions.json").read_text())
failures = (ROOT / "test" / "results" / "failures.txt").read_text()
summary = (ROOT / "test" / "results" / "summary.txt").read_text()
strict_path = ROOT / "test" / "results" / "summary_spark_strict.txt"
strict_summary = strict_path.read_text() if strict_path.exists() else None

passing = sorted(f for f, c in funcs.items() if not c.get("FAIL"))
failing = sorted(f for f, c in funcs.items() if c.get("FAIL"))
untested = sorted(f for f in docs if f not in funcs)

lines = ["# Spark 3.5 compatibility report", "",
         "Generated by `scripts/coverage_report.py` from the differential test run (`test/run_duckdb.py`).",
         "Every expected result comes from Apache Spark 3.5.9 (`test/make_golden.py`).", "",
         "## Totals", "",
         "`SET current_dialect = 'spark'` (lenient: also accepts DuckDB-only SQL, reported as LENIENT):", "",
         "```", summary.strip(), "```", ""] + ([
         "`SET current_dialect = 'spark_strict'` (a LENIENT result counts as a failure):", "",
         "```", strict_summary.strip(), "```", ""] if strict_summary else []) + [
         f"## Built-in functions ({len(docs)} in Spark 3.5)", "",
         f"- **{len(passing)}** pass every example from Spark's own documentation",
         f"- **{len(failing)}** have at least one failing example: {', '.join(f'`{f}`' for f in failing)}",
         f"- **{len(untested)}** have no documentation examples (operators and cast functions), "
         f"covered by `test/cases/operators.sql` and `test/cases/literals_types.sql`: "
         f"{', '.join(f'`{f}`' for f in untested)}", "",
         "## Remaining failures", ""]
blocks = [b for b in re.split(r"\n(?=FAIL |LENIENT )", failures) if b.strip()]
lenient = [b for b in blocks if b.startswith("LENIENT")]
if lenient:
    lines.insert(lines.index("## Remaining failures"), f"{len(lenient)} cases that Spark rejects are accepted by the "
                 "lenient `spark` dialect (DuckDB-only syntax); `spark_strict` rejects them all.\n")
for block in blocks:
    if block.startswith("LENIENT"):
        continue
    head, *rest = block.strip().split("\n")
    lines.append(f"- `{head}`")
    for r in rest[:3]:
        lines.append(f"  - {r.strip()[:300]}")
(ROOT / "COVERAGE.md").write_text("\n".join(lines) + "\n")
print("wrote COVERAGE.md")
