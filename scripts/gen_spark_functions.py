"""Generate src/include/spark_function_names.hpp from test/spark35_functions.txt (Spark 3.5 SHOW FUNCTIONS).

usage: python scripts/gen_spark_functions.py
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
names = sorted({line.strip().lower() for line in (ROOT / "test" / "spark35_functions.txt").read_text().splitlines()
                if line.strip()})
out = ["// Generated by scripts/gen_spark_functions.py from test/spark35_functions.txt (Apache Spark 3.5 built-in functions)",
       "#pragma once", "", "static const char *const SPARK_FUNCTION_NAMES[] = {"]
out += [f'    "{n}",' for n in names]
out += ["};", ""]
(ROOT / "src" / "include" / "spark_function_names.hpp").write_text("\n".join(out))
print(f"{len(names)} names")
