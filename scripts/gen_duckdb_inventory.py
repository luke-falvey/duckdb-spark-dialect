"""Write test/settings/duckdb_inventory.toml: DuckDB's settings (duckdb_settings()) classified for plan section B5.

usage: python scripts/gen_duckdb_inventory.py

`semantic` settings change SQL results and are run with a non-default value (`run_duckdb.py --duck-set key=value`)
over operators.sql, queries.sql and literals_types.sql: the Spark goldens are unchanged, so every case must pass.
Everything else is `inert` for the result of a query (resources, files, logging, extensions, ...).
"""
import duckdb

SEMANTIC = {
    "default_null_order": "nulls_first", "default_order": "desc", "integer_division": "true",
    "ieee_floating_point_ops": "false", "old_implicit_casting": "true", "default_collation": "nocase",
    "order_by_non_integer_literal": "true", "scalar_subquery_error_on_multiple_rows": "false",
    "lambda_syntax": "DISABLE_SINGLE_ARROW", "preserve_insertion_order": "false", "Calendar": "japanese", "threads": "1",
    "enable_optimizer": "false", "disabled_optimizers": "filter_pushdown",
    "arrow_lossless_conversion": "true", "force_bitpacking_mode": "constant", "ordered_aggregate_threshold": "1",
}


def main():
    con = duckdb.connect()
    names = [r[0] for r in con.execute("SELECT name FROM duckdb_settings() ORDER BY name").fetchall()]
    lines = ["# DuckDB settings classified for the leak check of docs/plans/spark-parity-testing.md B5 (generated by",
             "# scripts/gen_duckdb_inventory.py). `semantic` entries carry the non-default value the check sets.", ""]
    for n in names:
        lines.append(f'[settings."{n}"]')
        if n in SEMANTIC:
            lines += ['class = "semantic"', f'value = "{SEMANTIC[n]}"']
        else:
            lines += ['class = "inert"']
        lines.append("")
    open("test/settings/duckdb_inventory.toml", "w").write("\n".join(lines))
    print(f"{len(names)} settings, {len(SEMANTIC)} semantic")


if __name__ == "__main__":
    main()
