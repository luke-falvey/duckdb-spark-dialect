"""Generate test/cases/functions_examples.sql from the examples in Spark 3.5's own function docs
(DESCRIBE FUNCTION EXTENDED output, stored in test/spark35_function_docs.json)."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
docs = json.loads((ROOT / "test" / "spark35_function_docs.json").read_text())

# results that legitimately differ between runs or machines
NONDETERMINISTIC = {
    "rand", "randn", "random", "uuid", "shuffle", "current_date", "current_timestamp", "now", "curdate",
    "localtimestamp", "unix_timestamp", "monotonically_increasing_id", "spark_partition_id", "input_file_name",
    "input_file_block_start", "input_file_block_length", "version", "current_user", "user", "session_user",
    "current_timezone", "reflect", "java_method", "try_reflect", "uniform", "randstr",
}

lines = ["-- Generated by scripts/gen_function_cases.py from Spark 3.5 DESCRIBE FUNCTION EXTENDED examples.", ""]
for name, info in sorted(docs.items()):
    for sql in info.get("examples", []):
        lines.append(f"-- @function {name}")
        random_iv = name == "aes_encrypt" and "ECB" not in sql and "unhex(" not in sql
        if name in NONDETERMINISTIC or random_iv:
            lines.append("-- @nondeterministic")
        lines.append(sql + ";")
        lines.append("")
(ROOT / "test" / "cases" / "functions_examples.sql").write_text("\n".join(lines))
print("wrote", sum(len(i.get("examples", [])) for i in docs.values()), "cases")
