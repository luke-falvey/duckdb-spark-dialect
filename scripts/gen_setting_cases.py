"""Generate test/cases/settings/<key>.sql, one case file per semantic Spark setting (plan section B3).

usage: python scripts/gen_setting_cases.py

Every file starts with `-- @matrix <key>=<every legal value>` (plus `-- @config` lines for the settings the witness
requires), then the witness of the setting from docs/plans/spark-parity/conf_witnesses.json (its statements: all but the
last as `@setup`, the last compared), then the content of test/settings/extra/<short>.sql when that exists (the
hand-written coverage of tier 1 and 2 settings: every expression the setting touches, literals and columns, NULLs,
nesting, and a negative control).
"""
import json
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "test" / "cases" / "settings"
EXTRA = ROOT / "test" / "settings" / "extra"


def short(key):
    return key[len("spark.sql."):].replace(".", "_")


def main():
    inventory = tomllib.loads((ROOT / "test" / "settings" / "inventory.toml").read_text())["keys"]
    witnesses = {}
    for w in json.loads((ROOT / "docs" / "plans" / "spark-parity" / "conf_witnesses.json").read_text()):
        witnesses.setdefault(w["key"], []).append(w)
    OUT.mkdir(parents=True, exist_ok=True)
    written = 0
    for key, entry in sorted(inventory.items()):
        if entry["class"] != "semantic":
            continue
        values = list(dict.fromkeys([entry["default"], *entry["values"]]))
        seen_setup = set()
        lines = [f"-- Setting {key} (class {entry['class']}, tier {entry['tier']}). Generated by scripts/gen_setting_cases.py:",
                 "-- the witness from docs/plans/spark-parity/conf_witnesses.json, then test/settings/extra/" + short(key) + ".sql.",
                 f"-- @matrix {key}={','.join(values)}"]
        requires = {}
        for w in witnesses[key]:
            requires.update(w.get("requires") or {})
        for k, v in requires.items():
            lines.append(f"-- @config {k}={v}")
        lines.append("")
        for w in witnesses[key]:
            statements = list(w["statements"])
            for sql in statements[:-1]:
                if sql in seen_setup:
                    continue
                seen_setup.add(sql)
                lines += ["-- @setup", sql.rstrip(";") + ";", ""]
            lines += [statements[-1].rstrip(";") + ";", ""]
            for sql in w.get("cleanup", []):
                lines += ["-- @setup", sql.rstrip(";") + ";", ""]
        extra = EXTRA / (short(key) + ".sql")
        if extra.exists():
            lines.append(extra.read_text().rstrip() + "\n")
        (OUT / (short(key) + ".sql")).write_text("\n".join(lines))
        written += 1
    print(f"wrote {written} files to {OUT}")


if __name__ == "__main__":
    main()
