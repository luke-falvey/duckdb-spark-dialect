"""Write docs/plans/spark-parity/known_differences.md from test/xfail.toml: per xfail id the reason, the number of cases
and a reproducing example (the first case of the first entry). Also printed as a table for COVERAGE.md.

usage: python scripts/xfail_summary.py
"""
import sys
import tomllib
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "test"))
from harness import load_cases  # noqa: E402


def case_path(folded):
    for prefix in ("types__", "settings__", "spark_corpus__"):
        if folded.startswith(prefix):
            return ROOT / "test" / "cases" / prefix.rstrip("_") / folded[len(prefix):]
    return ROOT / "test" / "cases" / folded.replace("__", "/")


def expand(cases):
    out = []
    for c in cases:
        if isinstance(c, int):
            out.append(c)
        else:
            a, _, b = str(c).partition("-")
            out += list(range(int(a), int(b or a) + 1))
    return out


def main():
    entries = tomllib.loads((ROOT / "test" / "xfail.toml").read_text()).get("xfail", [])
    by_id = defaultdict(lambda: {"reason": "", "count": 0, "files": set(), "example": None})
    for e in entries:
        info = by_id[e["id"]]
        n = len(expand(e.get("cases", [])))
        info["reason"] = info["reason"] or e["reason"]
        info["count"] += n
        info["files"].add(e["file"])
        if info["example"] is None and n:
            first = expand(e["cases"])[0]
            path = case_path(e["file"])
            if path.exists():
                for c in load_cases([str(path)]):
                    if c.index == first:
                        info["example"] = f"{e['file']}:{first}  {c.sql.splitlines()[0][:160]}"
                        break
    lines = ["# Known differences from Spark 3.5 (generated by scripts/xfail_summary.py from test/xfail.toml)", "",
             "Each id is an expected failure of the differential tests: the case still runs and must keep failing; a case that "
             "starts to pass makes the run fail (XPASS) until its entry is removed. `conf-rejected`, `types-ntz` and "
             "`types-interval` are the classes plan section 9 allows; the other ids are open work or documented limits.", "",
             "| id | cases | files | reason | example |", "|---|---|---|---|---|"]
    for ident, info in sorted(by_id.items(), key=lambda kv: -kv[1]["count"]):
        lines.append(f"| `{ident}` | {info['count']} | {len(info['files'])} | {info['reason']} | `{info['example'] or ''}` |")
    out = ROOT / "docs" / "plans" / "spark-parity" / "known_differences.md"
    out.write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
