"""Promote inputs of Apache Spark's SQL test suite to gating case files under test/cases/spark_corpus/ (plan E.2).

usage: python scripts/promote_spark_corpus.py     (run `python test/fuzz/spark_corpus.py fetch` first)

Statements are split like Spark's SQLQueryTestSuite does; `--SET k=v` becomes `-- @config k=v`, `--IMPORT f.sql` inlines
the file, other `--` lines are dropped. DDL / DML / SET statements are `-- @setup`. The expected results are recorded
from live Spark (test/make_golden.py), not from Spark's golden `.out` files. The inputs are Apache-2.0 licensed (NOTICE).
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
INPUTS = ROOT / "test" / "fuzz" / "out" / "spark-sql-tests" / "sql" / "core" / "src" / "test" / "resources" / "sql-tests" / "inputs"
OUT = ROOT / "test" / "cases" / "spark_corpus"

NATIVE = ["arrayJoin", "binaryComparison", "booleanEquality", "caseWhenCoercion", "concat", "dateTimeOperations", "decimalPrecision",
          "division", "elt", "ifCoercion", "implicitTypeCasts", "inConversion", "mapZipWith", "mapconcat", "promoteStrings",
          "stringCastAndExpressions", "widenSetOperationTypes", "windowFrameCoercion"]
FILES = ([f"typeCoercion/native/{n}.sql" for n in NATIVE]
         + ["cast.sql", "try_cast.sql", "decimalArithmeticOperations.sql", "literals.sql", "interval.sql", "timezone.sql", "charvarchar.sql",
            "datetime-formatting.sql", "datetime-parsing.sql", "datetime-special.sql"]
         + [f"ansi/{p.name}" for p in sorted((INPUTS / "ansi").glob("*.sql"))]
         + [f"timestampNTZ/{p.name}" for p in sorted((INPUTS / "timestampNTZ").glob("*.sql"))])
SETUP = re.compile(r"^\s*(CREATE|DROP|INSERT|SET|USE|ALTER|TRUNCATE|REFRESH|CACHE|UNCACHE|ANALYZE|RESET)\b", re.I)


def read(rel, config, seen=()):
    """The statements of an input file with its imports inlined; --SET lines are collected into config."""
    path = INPUTS / rel
    lines = []
    for line in path.read_text().splitlines():
        m = re.match(r"--\s*SET\s+(\S+)\s*=\s*(\S+)", line)
        if m:
            config.append((m.group(1), m.group(2)))
            continue
        m = re.match(r"--\s*IMPORT\s+(\S+)", line)
        if m:
            # relative to the inputs directory (ansi/cast.sql imports the top-level cast.sql)
            target = m.group(1) if (INPUTS / m.group(1)).exists() else str(Path(rel).parent / m.group(1))
            lines.append(read(target, config))
            continue
        lines.append(line)
    return "\n".join(lines)


def split(text):
    """Statements separated by `;` outside quotes; `--` line comments and /* */ comments are removed."""
    text = re.sub(r"/\*.*?\*/", " ", text, flags=re.S)
    out, cur, quote, i = [], [], None, 0
    while i < len(text):
        ch = text[i]
        if quote:
            cur.append(ch)
            if ch == "\\" and i + 1 < len(text):
                cur.append(text[i + 1])
                i += 1
            elif ch == quote:
                quote = None
        elif ch in "'\"`":
            quote = ch
            cur.append(ch)
        elif ch == "-" and text.startswith("--", i):
            j = text.find("\n", i)
            i = len(text) if j < 0 else j
            continue
        elif ch == ";":
            out.append("".join(cur))
            cur = []
        else:
            cur.append(ch)
        i += 1
    out.append("".join(cur))
    return [re.sub(r"\n\s*\n", "\n", s.strip()) for s in out if s.strip()]


def main():
    if not INPUTS.exists():
        sys.exit("run `python test/fuzz/spark_corpus.py fetch` first")
    OUT.mkdir(parents=True, exist_ok=True)
    total = 0
    for rel in FILES:
        if not (INPUTS / rel).exists():
            print(f"missing {rel}")
            continue
        config = []
        # SQLQueryTestSuite runs these directories under a fixed setting
        if rel.startswith("ansi/"):
            config.append(("spark.sql.ansi.enabled", "true"))
        if rel.startswith("timestampNTZ/"):
            config.append(("spark.sql.timestampType", "TIMESTAMP_NTZ"))
        statements = split(read(rel, config))
        name = rel.replace("/", "__")
        lines = [f"-- Derived from Apache Spark v3.5.9 sql/core/src/test/resources/sql-tests/inputs/{rel} (Apache License 2.0, see NOTICE).",
                 "-- Generated by scripts/promote_spark_corpus.py. Expected results are recorded from live Spark."]
        seen = {}
        for k, v in config:
            seen[k] = v
        for k, v in seen.items():
            lines.append(f"-- @config {k}={v}")
        lines.append("")
        for s in statements:
            if SETUP.match(s):
                lines.append("-- @setup")
            lines.append(s.rstrip(";") + ";")
            lines.append("")
        (OUT / f"{name}").write_text("\n".join(lines))
        total += len(statements)
    print(f"promoted {len(FILES)} files, {total} statements")
    notice = ROOT / "NOTICE"
    line = ("test/cases/spark_corpus/: statements derived from the SQL test inputs of Apache Spark v3.5.9 "
            "(https://github.com/apache/spark, Apache License 2.0).\n")
    if not notice.exists() or line not in notice.read_text():
        with open(notice, "a") as f:
            f.write(line)


if __name__ == "__main__":
    main()
