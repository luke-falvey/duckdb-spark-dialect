"""Write test/cases/types/c15_composition.sql: every documented Spark function example with an argument wrapped in
the expression forms the dialect rewrites (coalesce, ifnull, nvl, nvl2, CASE, if, nullif, greatest, a scalar subquery,
array / struct round trips, a lambda), and read from a column.

Every wrapper is value preserving, so Spark's answer is the plain call's answer; a difference means a rewrite leaves a
trace where the wrapped expression is used (an alias read as a named argument, a lost type, a non-constant argument,
...). Expectations come from Spark (test/make_golden.py). Deterministic.

usage: python scripts/gen_composition_cases.py
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "test"))
sys.path.insert(0, str(ROOT / "test" / "fuzz"))
from args_sweep import SIMPLE_SELECT, load_seeds, slots, substitute  # noqa: E402

OUT = ROOT / "test" / "cases" / "types" / "c15_composition.sql"
MAX_SLOTS = 2

# {name: template over the original argument text v}
WRAPPERS = {
    "coalesce": "coalesce({v}, {v})",
    "ifnull": "ifnull({v}, {v})",
    "nvl": "nvl({v}, {v})",
    "nvl2": "nvl2({v}, {v}, {v})",
    "case": "CASE WHEN true THEN {v} END",
    "if": "if(true, {v}, {v})",
    "nullif": "nullif({v}, NULL)",
    "greatest": "greatest({v}, {v})",
    "subquery": "(SELECT {v})",
    "array": "array({v})[0]",
    "struct": "named_struct('f', {v}).f",
    "lambda": "transform(array({v}), e -> e)[0]",
}
# forms Spark rejects in an inline table (VALUES rows must be foldable): not used for a value there
NOT_IN_VALUES = {"subquery", "lambda"}
# slot kinds whose value Spark requires to be a literal or of a type the wrappers change (patterns are fine)
SKIP_KINDS = {"array", "map"}
COLUMN_WRAPPERS = {"column": "x", "column_coalesce": "coalesce(x, x)", "column_case": "CASE WHEN x IS NULL THEN x ELSE x END"}
# functions whose examples are not deterministic or depend on the session
SKIP_FUNCTIONS = {"current_date", "current_timestamp", "now", "rand", "random", "randn", "uuid", "shuffle",
                  "current_user", "user", "session_user", "current_catalog", "current_database", "current_schema",
                  "input_file_name", "monotonically_increasing_id", "spark_partition_id", "reflect", "java_method",
                  "try_reflect", "localtimestamp", "current_timezone", "version", "assert_true", "raise_error"}


def emit():
    lines = ["-- C15 composition: function arguments wrapped in rewritten expression forms (value preserving).",
             "-- Generated by scripts/gen_composition_cases.py; do not edit. Expectations come from Spark.", ""]
    n = 0
    taken = set()
    for fn, example in load_seeds():
        if fn in taken or fn in SKIP_FUNCTIONS:
            continue
        toks, sl = slots(example, fn)
        sl = [s for s in sl if s[2] not in SKIP_KINDS]
        if not sl:
            continue
        taken.add(fn)
        for idx, slot in enumerate(sl[:MAX_SLOTS]):
            original = " ".join(t for _, t in toks[slot[0]:slot[1]])
            in_values = any(t.upper() == "VALUES" for _, t in toks[:slot[0]])
            for name, template in WRAPPERS.items():
                if in_values and name in NOT_IN_VALUES:
                    continue
                sql = substitute(toks, {(slot[0], slot[1]): template.format(v=original)})
                lines.append(f"-- @compose {fn} slot={idx} form={name}")
                lines.append(sql.rstrip().rstrip(";") + ";")
                lines.append("")
                n += 1
            for name, template in COLUMN_WRAPPERS.items():
                sql = substitute(toks, {(slot[0], slot[1]): template})
                m = SIMPLE_SELECT.match(sql)
                if not m:
                    continue
                lines.append(f"-- @compose {fn} slot={idx} form={name}")
                lines.append(f"SELECT {m.group(1).rstrip().rstrip(';')} FROM VALUES ({original}), (NULL) AS t(x);")
                lines.append("")
                n += 1
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines))
    print(f"wrote {n} cases to {OUT}")


if __name__ == "__main__":
    emit()
